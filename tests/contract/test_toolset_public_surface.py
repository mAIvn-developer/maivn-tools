def test_top_level_toolset_exports_match_golden_surface() -> None:
    exported = tuple(sorted(name for name in maivn_tools.__all__ if name.endswith('ToolSet')))

    assert len(exported) == len(GOLDEN_TOOLSET_EXPORTS)
    assert set(exported) == set(GOLDEN_TOOLSET_EXPORTS)


def test_backend_helpers_are_public_exports() -> None:
    expected = {
        'MCPToolBackendExecutor',
        'MCPToolSetBackend',
        'NativeToolSetBackend',
        'ToolSetRegistration',
        'resolve_toolset_backend',
        'toolset_contract_specs',
    }

    assert expected <= set(maivn_tools.__all__)
